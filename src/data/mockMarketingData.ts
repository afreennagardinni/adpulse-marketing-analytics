// Generate 30 days of daily timeline data with realistic variance
export function generate30DaysTimeSeries(): TimeSeriesPoint[] {
  const points: TimeSeriesPoint[] = [];
  const now = new Date(2026, 9, 27, 8, 40, 0); // Oct 27, 2026

  for (let i = 29; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dayOfWeek = d.getDay();
    const weekendMultiplier = dayOfWeek === 0 || dayOfWeek === 6 ? 1.25 : 1.0;
    const randomVariation = 0.92 + Math.random() * 0.16;

    const baseSpend = 5100 * weekendMultiplier * randomVariation;
    const baseRoas = (4.5 + Math.sin(i / 3) * 0.45 + (Math.random() * 0.4 - 0.2));
    const baseRevenue = baseSpend * baseRoas;
    const baseClicks = Math.round(baseSpend / (0.55 + Math.random() * 0.08));
    const baseImpressions = Math.round(baseClicks * (28 + Math.random() * 8));
    const baseConversions = Math.round(baseRevenue / (62 + Math.random() * 12));

    const channels: MarketingChannel[] = ['Google Ads', 'Meta', 'TikTok', 'LinkedIn', 'YouTube', 'Email'];
    const channelBreakdown: Record<MarketingChannel, { spend: number; revenue: number }> = {
      'Google Ads': { spend: baseSpend * 0.35, revenue: baseSpend * 0.35 * 5.2 },
      'Meta': { spend: baseSpend * 0.28, revenue: baseSpend * 0.28 * 4.3 },
      'TikTok': { spend: baseSpend * 0.16, revenue: baseSpend * 0.16 * 3.4 },
      'LinkedIn': { spend: baseSpend * 0.12, revenue: baseSpend * 0.12 * 3.6 },
      'YouTube': { spend: baseSpend * 0.05, revenue: baseSpend * 0.05 * 2.5 },
      'Email': { spend: baseSpend * 0.04, revenue: baseSpend * 0.04 * 9.8 },
    };

    const monthStr = d.toLocaleString('en-US', { month: 'short' });
    const dayNum = d.getDate();

    points.push({
      id: `pt-${i}`,
      timestamp: d.getTime(),
      label: `${monthStr} ${dayNum}`,
      dateStr: d.toISOString().split('T')[0],
      spend: Math.round(baseSpend),
      revenue: Math.round(baseRevenue),
      roas: Number(baseRoas.toFixed(2)),
      impressions: baseImpressions,
      clicks: baseClicks,
      conversions: baseConversions,
      channelBreakdown,
    });
  }

  return points;
}

